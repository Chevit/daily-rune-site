function runePage(l, i) {
  const rune = RUNES[i];
  const R = LOCALES[l].runes[rune.id];
  const path = `/runes/${rune.id}/`;
  const isBlank = rune.id === 'blank';
  const h1 = (isBlank && BLANK[l].h1) || T[l].h1(R.name);
  const title = withSuffix(l, isBlank ? BLANK[l].title : T[l].title(R.name, rune.isReversible));
  const prev = RUNES[(i - 1 + RUNES.length) % RUNES.length];
  const next = RUNES[(i + 1) % RUNES.length];
  const nameOf = r => LOCALES[l].runes[r.id].name;

  const reversed = rune.isReversible
    ? `      <h2 id="reversed">${T[l].reversed}</h2>
${paras(R.reversedMeaning)}\n`
    : '';

  return `${head(l, {
    title, desc: describe(R.uprightMeaning), path, ogType: 'article',
    ld: {
      '@context': 'https://schema.org',
      '@type': 'Article',
      headline: h1,
      inLanguage: T[l].lang,
      url: url(l, path),
      isPartOf: { '@type': 'WebSite', name: 'Daily Rune', url: `${SITE}/` },
      about: { '@type': 'Thing', name: `${LOCALES.en.runes[rune.id].name} (Elder Futhark rune)` },
    },
  })}
<body>
  <div class="page page--wide">

    <header class="site-header">
${localeToggle(l, path)}
      <h1 class="app-title subpage-title">${esc(h1)}</h1>
      <a href="${T[l].prefix}/runes/" class="back-link">${esc(T[l].allRunes)}</a>
    </header>

    <article class="content-card subpage-content">
      <div class="rune-page-glyph rune-glyph">${rune.unicodeSymbol}</div>
      <div class="keywords">
${R.keywords.map(k => `        <span class="keyword">${esc(k)}</span>`).join('\n')}
      </div>
      <h2>${T[l].upright}</h2>
${paras(R.uprightMeaning)}
${reversed}      <nav class="rune-pager">
        <a href="${T[l].prefix}/runes/${prev.id}/">← ${esc(nameOf(prev))}</a>
        <a href="${T[l].prefix}/runes/${next.id}/">${esc(nameOf(next))} →</a>
      </nav>
    </article>

    <div class="divider"></div>

${footer(l)}

  </div>
</body>
</html>
`;
}

function hubPage(l) {
  const path = '/runes/';
  const items = RUNES.map(r => {
    const R = LOCALES[l].runes[r.id];
    return `        <a class="rune-tile" href="${T[l].prefix}/runes/${r.id}/">
          <span class="rune-tile-glyph">${r.unicodeSymbol}</span>
          <span class="rune-tile-name">${esc(R.name)}</span>
          <span class="rune-tile-keyword">${esc(R.keywords[0])}</span>
        </a>`;
  }).join('\n');

  return `${head(l, {
    title: T[l].hubTitle, desc: T[l].hubDesc, path, ogType: 'website',
    ld: {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      name: T[l].hubH1,
      inLanguage: T[l].lang,
      url: url(l, path),
      isPartOf: { '@type': 'WebSite', name: 'Daily Rune', url: `${SITE}/` },
    },
  })}
<body>
  <div class="page page--wide">

    <header class="site-header">
${localeToggle(l, path)}
      <h1 class="app-title subpage-title">${esc(T[l].hubH1)}</h1>
      <a href="${T[l].prefix}/" class="back-link">${esc(T[l].home)}</a>
    </header>

    <div class="content-card">
      <nav class="rune-grid">
${items}
      </nav>
    </div>

    <div class="divider"></div>

${footer(l)}

  </div>
</body>
</html>
`;
}

function sitemap() {
  const alt = path => ['en', 'ua'].map(l => `    <xhtml:link rel="alternate" hreflang="${T[l].lang}" href="${url(l, path)}"/>`)
    .concat(`    <xhtml:link rel="alternate" hreflang="x-default" href="${url('en', path)}"/>`).join('\n');
  const entry = (loc, path) => `  <url>
    <loc>${loc}</loc>
${path ? alt(path) + '\n' : ''}    <lastmod>${TODAY}</lastmod>
  </url>`;
  const paired = ['/', '/runes/', ...RUNES.map(r => `/runes/${r.id}/`)];
  const urls = [
    ...paired.flatMap(p => [entry(url('en', p), p), entry(url('ua', p), p)]),
    ...['/support.html', '/privacy-policy.html', '/terms-of-use.html'].map(p => entry(`${SITE}${p}`)),
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join('\n')}
</urlset>
`;
}

function write(rel, content) {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content, 'utf8');
}

for (const l of ['en', 'ua']) {
  const dir = l === 'ua' ? 'uk/' : '';
  RUNES.forEach((r, i) => write(`${dir}runes/${r.id}/index.html`, runePage(l, i)));
  write(`${dir}runes/index.html`, hubPage(l));
}
write('sitemap.xml', sitemap());
write('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`);
console.log(`✓ wrote ${RUNES.length * 2} rune pages, 2 hubs, sitemap.xml, robots.txt`);
