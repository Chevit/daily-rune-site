// Blank rune: locale name reads badly inside the templates.
const BLANK = {
  en: { title: 'Blank Rune (Odin) Meaning', h1: null },
  ua: { title: 'Порожня руна: значення', h1: 'Порожня руна — значення' },
};

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const paras = text => text.split('\n\n').map(p => `      <p>${esc(p)}</p>`).join('\n');
const jsonLd = obj => JSON.stringify(obj, null, 2).replace(/</g, '\\u003c');
const other = l => (l === 'en' ? 'ua' : 'en');
const url = (l, path) => `${SITE}${T[l].prefix}${path}`;

function withSuffix(l, title) {
  const full = `${title} | ${T[l].site}`;
  return full.length <= 65 ? full : title;
}

// Whole sentences until ≥70 chars, then cut at a word boundary to ≤155 + "…".
function describe(text) {
  const sentences = text.replace(/\n+/g, ' ').split(/(?<=[.!?…])\s+/);
  let out = '';
  for (const s of sentences) {
    out = out ? `${out} ${s}` : s;
    if (out.length >= 70) break;
  }
  if (out.length <= 155) return out;
  return out.slice(0, 155).replace(/\s+\S*$/, '').replace(/[\s,;:—–-]+$/, '') + '…';
}

