    h1: n => `${n} — значення руни`,
    title: (n, rev) => rev ? `Руна ${n}: значення, пряме й перевернуте` : `Руна ${n}: значення — Старший Футарк`,
    hubH1: 'Значення рун Старшого Футарку',
